#!/usr/bin/env python3
"""Check the Teardown Index tables and rebuild the headline figures.

Reads data/raw/*.csv, writes:
  data/derived/headline.json   the headline figures
and refreshes the headline block in README.md.

The tables in data/raw/ are the published output of the scoring pipeline
(GUR scrape of 30 Oct 2026, family de-duplication, weighting, bootstrap).
That pipeline is not in this repository yet; this script recomputes every
derived figure the page shows from those tables, so the page, the README and
this script always agree.

Standard library only. Run from the repository root:  python scripts/build.py
"""
import csv
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RAW = os.path.join(ROOT, "data", "raw")
OUT = os.path.join(ROOT, "data", "derived")
EU_MEMBERS = ["Germany", "Netherlands", "France", "Italy", "Ireland", "Sweden"]
METHODS = ["group", "strict", "hq"]


def read(name):
    with open(os.path.join(RAW, name), newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def main():
    index = read("index.csv")
    stats = {r["metric"]: float(r["value"]) for r in read("stats.csv")}
    ratio = {r["firm"]: float(r["ratio"]) for r in read("ratio.csv")}
    cross = {r["measure"]: r for r in read("crosscheck.csv")}

    problems = []
    for m in METHODS:
        rows = [r for r in index if r["method"] == m]
        if not any(r["country"] == "EU total" for r in rows):
            problems.append(f"method '{m}' has no 'EU total' row")
        for r in rows:
            lo, v, hi = float(r["ci_low"]), float(r["index_share"]), float(r["ci_high"])
            if not lo <= v <= hi:
                problems.append(f"{m}/{r['country']}: index {v} outside its range {lo}-{hi}")

    def row(m, c):
        return next(r for r in index if r["method"] == m and r["country"] == c)

    eu = row("group", "EU total")
    eu_share = float(eu["index_share"])
    ahead = [r for r in index if r["method"] == "group" and r["country"] != "EU total"
             and r["country"] not in EU_MEMBERS and float(r["index_share"]) > eu_share]

    headline = {
        "edition": 1,
        "gur_snapshot": "2026-10-30",
        "eu_index_group": eu_share,
        "eu_range_group": [float(eu["ci_low"]), float(eu["ci_high"])],
        "eu_rank": len(ahead) + 1,
        "ahead_of_eu": [r["country"] for r in ahead],
        "us_index_group": float(row("group", "United States")["index_share"]),
        "china_index_group": float(row("group", "China")["index_share"]),
        "eu_index_strict": float(row("strict", "EU total")["index_share"]),
        "eu_index_hq": float(row("hq", "EU total")["index_share"]),
        "attribution_delta": round(eu_share - float(row("hq", "EU total")["index_share"]), 5),
        "eu_family_incidence": float(eu["incidence"]),
        "components": int(stats["components"]),
        "weapon_families": int(stats["weapon_families"]),
        "post_2022_share_of_dated": round(stats["dated_2022_on"] / stats["dated"], 4),
        "date_parser_exact_rate": round(stats["calib_exact"] / stats["calib_parsed"], 4),
        "size_ratio": {k: ratio[k] for k in ("STMicroelectronics", "Infineon", "NXP", "u-blox")},
        "us_share_vs_rusi_2022": [float(cross["United States share of foreign parts"]["gur"]),
                                  float(cross["United States share of foreign parts"]["rusi_2022"])],
        "checks_failed": problems,
    }

    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "headline.json"), "w", encoding="utf-8", newline="\n") as f:
        json.dump(headline, f, indent=2)
        f.write("\n")
    update_readme(headline)
    print(json.dumps(headline, indent=2))
    if problems:
        raise SystemExit("Checks failed:\n" + "\n".join(problems))


def pct(x):
    return f"{x * 100:.1f}%"


def update_readme(h):
    path = os.path.join(ROOT, "README.md")
    if not os.path.exists(path):
        return
    lo, hi = h["eu_range_group"]
    block = (
        "<!-- HEADLINE:START (generated by scripts/build.py, do not edit by hand) -->\n"
        f"**Traced to parent companies, EU firms make {pct(h['eu_index_group'])} of the weighted foreign "
        f"parts in Russian weapons** (90% range {pct(lo)} to {pct(hi)}), second only to the United States "
        f"({pct(h['us_index_group'])}). GUR's own headquarters labels put the EU at {pct(h['eu_index_hq'])}.\n\n"
        f"Based on {h['components']:,} components in {h['weapon_families']} weapon families "
        f"(GUR snapshot {h['gur_snapshot']}). {pct(h['post_2022_share_of_dated'])} of dated parts were made "
        f"in 2022 or later.\n"
        "<!-- HEADLINE:END -->"
    )
    text = open(path, encoding="utf-8").read()
    new = re.sub(r"<!-- HEADLINE:START.*?<!-- HEADLINE:END -->", block, text, flags=re.S)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(new)


if __name__ == "__main__":
    main()
